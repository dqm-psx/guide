const {test,expect} = require('@playwright/test');
let url, fixture;
test.beforeAll(async () => {
  fixture = await import('../helpers/psx-save');
  url = await (await import('../helpers/modes')).startGuideServer();
});
test.afterAll(async () => { await (await import('../helpers/modes')).stopGuideServer(); });

test('a card slot keeps its own inventory, registered species and keys after reload', async ({page}) => {
  await page.setViewportSize({width:360,height:800});
  await page.goto(url+'#team-planner?import=save');
  const original = await page.locator('#planner-team-select').inputValue();
  const tara = fixture.adventureBlock(2);
  tara.writeUInt16LE(8,0x1f14);
  fixture.putBits(tara,0x1ef0,0x1d,1,1);
  const card = fixture.card([[1,1,fixture.block()],[2,5,fixture.finishBlock(tara)]]);
  await page.locator('#save-import-file').setInputFiles({name:'card.mcd',mimeType:'application/octet-stream',buffer:card});
  await page.locator('#save-import-slot').selectOption({index:1});
  await page.locator('#save-import-apply').click();
  const tab = page.getByRole('tab',{name:'Adventure log'});
  await tab.click();
  const log = page.locator('#planner-adventure');
  await expect(log).toContainText('19h 12m');
  await expect(log).toContainText('543,210 G');
  await expect(log.locator('li').filter({has:page.getByRole('link',{name:'Medicinal Herb',exact:true})})).toContainText('×2');
  await expect(log.locator('li').filter({has:page.getByRole('link',{name:'Amor Water',exact:true})})).toContainText('×24');
  await expect(log).toContainText('5 / 312');
  await expect(log).toContainText('Pirate Key');
  await expect(log.getByRole('link',{name:'Bazaar',exact:true})).toHaveAttribute('href','#atlas?map=map-8-0');
  await expect(log.getByRole('link',{name:'B',exact:true})).toHaveAttribute('href','#field-guide?kind=quest&entry=quest-arena-dqm2-b');
  await log.getByText('1 appraised · 1 mysterious',{exact:true}).click();
  await expect(log).toContainText('Brif Desert Key');
  await log.locator('details[data-family="0"] summary').click();
  await expect(log.locator('[data-library-families] a[href="#monster?id=0"]')).toBeVisible();
  await log.getByLabel('Show',{exact:true}).selectOption('missing');
  await expect(log.locator('[data-library-families] a[href="#monster?id=0"]')).toHaveCount(0);
  await expect(log.locator('[data-library-families] a[href="#monster?id=1"]')).toHaveCount(1);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(360);
  await page.reload();
  await expect(log.getByRole('heading',{name:'Unhatched eggs 2'})).toBeVisible();
  await expect(log.getByRole('link',{name:'Aibou'})).toHaveAttribute('href','#monster?id=323');
  await log.getByText('Monster details',{exact:true}).click();
  await expect(log.locator('.log-extra-list .planner-card-attributes dt')).toHaveCount(6);
  await page.getByRole('tab',{name:'My monsters'}).click();
  await page.locator('#planner-data-tools summary').first().click();
  const downloading = page.waitForEvent('download');
  await page.locator('#planner-export').click();
  const download = await downloading;
  const read = await download.createReadStream(), chunks = [];
  for await (const chunk of read) chunks.push(chunk);
  const teamFile = {name:'Tara team.json',mimeType:'application/json',buffer:Buffer.concat(chunks)};
  await page.getByRole('tab',{name:'Adventure log'}).click();
  await page.locator('#planner-game-dqm1').click();
  await expect(page.locator('#planner-team-select')).toHaveValue(original);
  await expect(log.getByRole('heading',{name:'No Adventure log for this team'})).toBeVisible();
  await expect(log).not.toContainText('543,210');
  await page.getByRole('tab',{name:'My monsters'}).click();
  await page.locator('#planner-import').setInputFiles(teamFile);
  await expect(page.locator('#planner-team-select option:checked')).toHaveText('Tara team');
  await page.getByRole('tab',{name:'Adventure log'}).click();
  await expect(log).toContainText('543,210 G');
  await expect(log).toContainText('Tara · Story complete');
});

test('a valid early save with no importable monsters still opens its Adventure log', async ({page}) => {
  const bytes = fixture.adventureBlock();
  for(let i=0;i<50;i++) bytes[0x250+i*136+0x7c]=255;
  bytes[0x150]&=0xfc;
  fixture.finishBlock(bytes);
  await page.goto(url+'#team-planner?import=save');
  await page.locator('#save-import-file').setInputFiles({name:'early.sav',mimeType:'application/octet-stream',buffer:bytes});
  await page.locator('#save-import-apply').click();
  await expect(page.getByRole('tab',{name:'Adventure log'})).toBeFocused();
  await expect(page.locator('#planner-adventure')).toContainText('12,345 G');
  await expect(page.locator('#planner-adventure')).not.toContainText('Magic keys');
});
